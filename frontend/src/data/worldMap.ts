// Equirectangular projection: lon->x, lat->y
export function project(lat: number, lon: number, w = 1000, h = 500): { x: number; y: number } {
  const x = ((lon + 180) / 360) * w;
  const y = ((90 - lat) / 180) * h;
  return { x, y };
}

